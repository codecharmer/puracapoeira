					<!-- /wp:list-item -->
					<!-- wp:list-item -->
					<li><em>Cuenta de miembro.</em> Desde la versión 0.2.0 la app se usa con una cuenta; en la versión anterior la cuenta es opcional. Guardamos tu correo y lo que escribes en tu perfil: tu apelido, tu fecha de nacimiento y, si los das, tu nombre completo, tu teléfono, tu sexo, tu corda y tu sede. Guardamos también si tu membresía del mes está pagada (lo registra tu sede; la app no cobra). Si entras con Apple o Google recibimos de ellos tu correo y un identificador; de Google, además, tu nombre y la dirección de tu foto de perfil; de Apple, la autorización que nos permite revocar ese acceso cuando eliminas tu cuenta. Tu apelido, tu corda y tu sede los ven los profesores y la administración de la escuela. Tu nombre completo y tu contacto solo los ven la administración de tu sede y la de la escuela. Al iniciar sesión, el identificador de notificaciones de tu teléfono queda vinculado a tu cuenta. Las cuentas propias son a partir de los 13 años y usamos tu fecha de nacimiento para comprobarlo. Puedes exportar tus datos y eliminar tu cuenta en la app (Más → Mi cuenta → Mis datos): se borran tus datos personales y los registros de pago y de asistencia de la escuela se conservan sin tu nombre.</li>
					<!-- /wp:list-item -->
					<!-- wp:list-item -->
					<li><em>Asistencia.</em> Guardamos los días en que entrenaste en tu sede. Los registras tú en la app ("Registrar mi asistencia") o los marca tu profesor al pasar lista. De cada día guardamos la sede, la fecha, quién lo registró y cuándo. Tú ves tus días en Mi cuenta. Los ven también los profesores y la administración de tu sede, y la administración de la escuela.</li>
