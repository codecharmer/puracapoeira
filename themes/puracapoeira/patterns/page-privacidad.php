					<!-- /wp:list-item -->
					<!-- wp:list-item -->
					<li><em>Attendance.</em> We store the days you trained at your location. You record them yourself in the app ("Record my attendance") or your instructor marks them when taking attendance. For each day we store the location, the date, who recorded it and when. You see your days in My account. The instructors and administration of your location, and the school's administration, see them too.</li>
					<li><em>Your children.</em> If your children train at the school, you can add them from your account (More → My account → My children). A child has no account and does not use the app: you enter their name, their apelido if they have one, their date of birth, their corda and the location where they train. We also store whether their month's membership is paid and the days they trained, as for any member. Their name or apelido and their corda are seen by the instructors and administration of their location, together with your apelido as their parent or guardian; the administration of their location and the school's also see your phone and email, so they can reach you. You see their details, membership and attendance under My children, and you can change or remove them at any time: when you remove a child or delete your account, their name and details are erased and the school's payment and attendance records are kept without the name. If you say that you do not train yourself, you are not on your location's list of students.</li>
